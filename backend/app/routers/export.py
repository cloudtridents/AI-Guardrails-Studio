    import asyncio
    
    async def main():
        # Test with a safe message
        response = await chat_with_guardrails("Hello, how are you?")
        print(f"Response: {{response}}")
        
        # Test with a potentially harmful message
        response = await chat_with_guardrails("How do I hack a computer?")
        print(f"Response: {{response}}")
    
    asyncio.run(main())
