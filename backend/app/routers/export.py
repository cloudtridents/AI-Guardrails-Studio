"""API routes for Export/Deploy Pipeline."""

from fastapi import APIRouter, HTTPException

from app.services import agent_store, config_store

router = APIRouter()


@router.post("/agent/{agent_id}")
async def export_agent(agent_id: str):
    """Generate a deployable package for an agent."""
    agent = agent_store.get_agent(agent_id)
    if not agent:
        raise HTTPException(status_code=404, detail="Agent not found")

    # Collect guardrail configs
    input_configs = []
    for cid in agent.get_input_guardrail_ids():
        c = config_store.get_config(cid)
        if c:
            input_configs.append(c)

    output_configs = []
    for cid in agent.get_output_guardrail_ids():
        c = config_store.get_config(cid)
        if c:
            output_configs.append(c)

    # Generate NeMo config files
    nemo_configs = _generate_nemo_configs(agent, input_configs, output_configs)

    # Generate Docker Compose
    docker_compose = _generate_docker_compose(agent)

    # Generate Kubernetes YAML
    kubernetes_yaml = _generate_kubernetes_yaml(agent)

    # Generate Python SDK snippet
    python_sdk_snippet = _generate_python_sdk_snippet(agent, input_configs, output_configs)

    # Generate README
    readme = _generate_readme(agent, input_configs, output_configs)

    return {
        "agent_id": agent_id,
        "agent_name": agent.name,
        "docker_compose": docker_compose,
        "kubernetes_yaml": kubernetes_yaml,
        "python_sdk_snippet": python_sdk_snippet,
        "nemo_config_files": nemo_configs,
        "readme": readme,
    }


def _generate_nemo_configs(agent, input_configs, output_configs) -> dict:
    """Generate production NeMo Guardrails config files."""
    configs = {}

    # Main config.yml
    main_config = f"""# NeMo Guardrails Configuration for: {agent.name}
# Generated by NeMo Guardrails Testing Platform

models:
  - type: main
    engine: {agent.provider}
    model: {agent.model}
"""

    if agent.temperature != 0.7:
        main_config += f"    parameters:\n      temperature: {agent.temperature}\n"

    if agent.api_base:
        main_config += f"    parameters:\n      api_base: {agent.api_base}\n"

    main_config += f"""
instructions:
  - type: general
    content: |
      {agent.system_prompt}

rails:
  input:
    flows:
"""
    for cfg in input_configs:
        main_config += f"      - {cfg.name.lower().replace(' ', '_')}\n"

    main_config += "  output:\n    flows:\n"
    for cfg in output_configs:
        main_config += f"      - {cfg.name.lower().replace(' ', '_')}\n"

    configs["config.yml"] = main_config

    # Generate individual rail configs
    for i, cfg in enumerate(input_configs + output_configs):
        if cfg.colang_content.strip():
            configs[f"rails/{cfg.name.lower().replace(' ', '_')}.co"] = cfg.colang_content
        if cfg.prompts_content.strip():
            configs[f"prompts/{cfg.name.lower().replace(' ', '_')}_prompts.yml"] = cfg.prompts_content

    return configs


