from nemoguardrails import RailsConfig, LLMRails

# Load configuration from directory
config = RailsConfig.from_path("./config")
rails = LLMRails(config)


async def chat_with_guardrails(user_message: str, history: list = None):
    """Send a message through the guardrails pipeline."""
    messages = []
    
    if history:
        for msg in history:
            messages.append({{"role": msg["role"], "content": msg["content"]}})
    
    messages.append({{"role": "user", "content": user_message}})
    
    # Generate response with guardrails applied
    response = await rails.generate_async(messages=messages)
    
    return response


# ─── FastAPI Integration Example ──────────────────────────────────────────────

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel

app = FastAPI(title="{agent.name} API")


class ChatRequest(BaseModel):
    message: str
    history: list = []


class ChatResponse(BaseModel):
    response: str
    blocked: bool = False


@app.post("/chat", response_model=ChatResponse)
async def chat(request: ChatRequest):
    """Chat endpoint with guardrails protection."""
    try:
        response = await chat_with_guardrails(request.message, request.history)
        
        # Check if blocked
        response_text = response.get("content", str(response))
        blocked = _is_blocked(response_text)
        
        return ChatResponse(response=response_text, blocked=blocked)
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


def _is_blocked(text: str) -> bool:
    """Check if the response indicates the message was blocked."""
    blocked_phrases = [
        "i'm sorry, i can't",
        "i cannot help with that",
        "i'm not able to help",
    ]
    return any(phrase in text.lower() for phrase in blocked_phrases)


